import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const browser = await chromium.launch({ channel:'chrome',headless:true })
const context = await browser.newContext({viewport:{width:390,height:844}})
const page = await context.newPage()
page.setDefaultTimeout(10000)
const errors=[]
page.on('pageerror',e => errors.push(e.message))
const url=new URL('../index.html',import.meta.url).href
const out=fileURLToPath(new URL('../../output/playwright/',import.meta.url))
mkdirSync(out,{recursive:true})
try {
  await page.goto(url)
  await page.getByText('Modo archivo',{exact:false}).waitFor()
  await page.getByRole('button',{name:'Cerrar sesión',exact:true}).click()
  await page.getByLabel('Nombre de usuario').fill('pastor_maldonado')
  await page.getByLabel('Contraseña').fill('demo1234')
  await page.getByRole('button',{name:'Ingresar a la plataforma'}).click()
  await page.getByRole('button',{name:/Congregación Maldonado/}).click()
  await page.getByRole('heading',{name:'Inicio',exact:true}).waitFor()
  assert.equal(await page.locator('.chart-card').count(),0)
  for(const width of [360,390,768,1440]) {
    await page.setViewportSize({width,height:900})
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,`Inicio sin desbordamiento ${width}`)
    await page.screenshot({path:`${out}/nuevo-inicio-${width}.png`,fullPage:true})
  }
  await page.setViewportSize({width:390,height:844})
  await page.goto(`${url}#/cultos`)
  await page.getByRole('heading',{name:'Cultos y asistencia'}).waitFor()
  await page.locator('.schedule-configuration summary').click()
  await page.getByRole('button',{name:'Agregar horario',exact:true}).click()
  await page.getByText('Horario guardado.',{exact:false}).waitFor()
  await page.locator('.schedule-chip').first().click()
  const list=page.getByRole('dialog',{name:'Tomar asistencia'})
  await list.waitFor()
  await list.locator('.attendance-focus-person').first().click()
  await list.getByRole('button',{name:'Añadir amigo'}).click()
  await list.getByLabel('Nombre y apellido').fill('VisitanteQA')
  await list.getByRole('button',{name:'Guardar y marcar presente'}).click()
  await list.getByText('VisitanteQA',{exact:true}).waitFor()
  await list.getByRole('button',{name:'Guardar asistencia',exact:true}).click()
  await list.getByText('Asistencia guardada.',{exact:true}).waitFor()
  await page.screenshot({path:`${out}/nueva-asistencia-390.png`})
  await list.getByRole('button',{name:'Cerrar toma de asistencia'}).click()
  const count=await page.locator('.attendance-history .work-row').count()
  await page.locator('.schedule-chip').first().click()
  await list.getByText('VisitanteQA',{exact:true}).waitFor()
  assert.equal(await list.locator('.attendance-focus-person').filter({hasText:'VisitanteQA'}).getByRole('checkbox').isChecked(),true)
  await list.getByRole('button',{name:'Cerrar toma de asistencia'}).click()
  assert.equal(await page.locator('.attendance-history .work-row').count(),count,'No duplicar culto al pasar lista otra vez')
  await page.goto(`${url}#/informes`)
  await page.getByRole('heading',{name:'Informes',exact:true}).waitFor()
  assert.ok(await page.locator('.chart-card').count() >= 5)
  for(const width of [360,390,768,1440]) {
    await page.setViewportSize({width,height:900})
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,`Informes sin desbordamiento ${width}`)
  }
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:/(Crear|Abrir) informe mensual/}).click()
  const studio=page.getByRole('dialog',{name:'Informe mensual',exact:true})
  await studio.waitFor()
  const initialPages = await page.locator('#report-print-root .paper-page').count()
  await studio.getByLabel('Secretaría',{exact:true}).fill('Secretaría QA')
  await studio.getByLabel('Observaciones generales del informe').fill('Borrador conservado de prueba.')
  await studio.getByRole('button',{name:'Agregar página de evento'}).click()
  await studio.getByLabel('Título de la actividad').fill('Encuentro de prueba QA')
  await studio.getByLabel('Descripción del evento').fill('Una actividad documentada con su propia página.')
  await studio.getByRole('button',{name:'Guardar borrador'}).click()
  await studio.getByText('Borrador guardado.',{exact:false}).waitFor()
  await page.screenshot({path:`${out}/nuevo-editor-390.png`})
  await studio.getByRole('button',{name:'Cerrar editor de informes'}).click()
  await page.reload()
  await page.getByRole('button',{name:'Abrir informe mensual',exact:true}).click()
  await studio.waitFor()
  assert.equal(await studio.getByLabel('Secretaría',{exact:true}).inputValue(),'Secretaría QA')
  assert.equal(await studio.getByLabel('Observaciones generales del informe').inputValue(),'Borrador conservado de prueba.')
  assert.equal(await page.locator('#report-print-root .paper-page').count(),initialPages+1)
  assert.match(await page.locator('#report-print-root').innerText(), /Encuentro de prueba QA/)
  await page.setViewportSize({width:1440,height:1000})
  await page.screenshot({path:`${out}/nuevo-editor-1440.png`})
  await page.pdf({path:`${out}/informe-nuevo-prueba.pdf`,format:'A4',printBackground:true,preferCSSPageSize:true})
  await studio.getByRole('button',{name:'Enviar informe',exact:true}).click()
  await studio.getByRole('button',{name:'Confirmar envío'}).click()
  await studio.getByText('Informe enviado.',{exact:false}).waitFor()
  await studio.getByRole('button',{name:'Cerrar editor de informes'}).click()
  assert.equal(await page.locator('.report-history-row').filter({hasText:'Informe mensual'}).count(),1,'Guardar y enviar no duplica el informe')
  await page.getByRole('button',{name:/(Crear|Abrir) informe cuatrimestral/}).click()
  await page.getByRole('dialog',{name:'Informe cuatrimestral',exact:true}).waitFor()
  assert.deepEqual(errors,[])
  console.log('PASS: Inicio separado, móvil 360/390/768/1440, asistencia modal, amigo con nombre, no duplicados, borrador recuperado, páginas PDF, envío y cuatrimestral.')
} finally { await browser.close() }
