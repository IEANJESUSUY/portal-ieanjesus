// Versión real sin datos: abrir, registrar la primera congregación y entrar a su espacio.
import { phone, portableUrl, run, shots } from './utiles.mjs'

await run('Primer uso, sin datos', async ({ browser, check, watch }) => {
  const page = await (await browser.newContext(phone)).newPage()
  watch(page)
  await page.goto(portableUrl)
  await page.getByRole('button', { name: /Abrir preparación local/ }).click()
  await page.locator('.nd').waitFor()
  check(await page.getByText('Todavía no hay congregaciones').count() === 1, 'el panel vacío explica qué hacer primero')
  check(await page.locator('.nd-alerts li').count() === 0, 'sin iglesias no hay alertas falsas')
  await page.screenshot({ path: `${shots}/vacio-panel.png`, fullPage: true })
  await page.getByRole('link', { name: 'Registrar una congregación' }).click()
  await page.getByRole('button', { name: /Nuevo registro/ }).click()
  const dialog = page.locator('dialog[open]')
  await dialog.getByLabel(/^Nombre/).first().fill('Congregación Maldonado')
  const city = dialog.getByLabel(/Ciudad/)
  if (await city.count()) await city.first().fill('Maldonado')
  const pastor = dialog.getByLabel(/Pastor/)
  if (await pastor.count()) await pastor.first().fill('Pastor de Maldonado')
  await dialog.getByRole('button', { name: /Guardar/ }).click()
  await page.waitForTimeout(500)
  check((await page.locator('.crm-table').innerText()).includes('Congregación Maldonado'), 'la congregación queda registrada')
  await page.locator('button[title^="Cambiar de espacio"]').first().click()
  await page.getByRole('button', { name: /Congregación Maldonado/ }).click()
  await page.getByRole('button', { name: 'Saltar' }).click()
  await page.getByText('Dios te bendiga').waitFor()
  check(true, 'se entra al espacio de la congregación con su Inicio')
  await page.locator('.mobile-bottom-nav').getByRole('link', { name: 'Personas' }).click()
  check(await page.getByRole('button', { name: /Importar del formulario/ }).count() === 1, 'Personas ofrece importar el formulario de Google')
  await page.locator('.mobile-bottom-nav').getByRole('link', { name: 'Dinero' }).click()
  check((await page.locator('.fixed-expenses').innerText()).includes('Internet'), 'Dinero muestra los servicios fijos para anotar')
  await page.screenshot({ path: `${shots}/vacio-dinero.png`, fullPage: true })
})
